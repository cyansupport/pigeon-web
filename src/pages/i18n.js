  function resolve(pref, systemLocale) {
    if (pref && pref !== 'auto' && S[pref]) return pref;
    const code = String(systemLocale || 'en').toLowerCase().slice(0, 2);
    return S[code] ? code : 'en';
  }

  // Rewrites Windows key names for macOS: "Ctrl+Shift+T" -> "⌘⇧T", "<kbd>Ctrl</kbd>+<kbd>T</kbd>" -> "<kbd>⌘</kbd><kbd>T</kbd>".
  function macKeys(s) {
    return String(s)
      .replace(/<kbd>(Ctrl|Strg)<\/kbd>\+/g, '<kbd>⌘</kbd>')
      .replace(/\b(Ctrl|Strg)\+/g, '⌘')
      .replace(/\b(Shift|Umschalt|Mayús|Maj)\+/g, '⇧')
      .replace(/\bAlt\+/g, '⌥');
  }

  function make(lang, { mac = false } = {}) {
    const table = S[lang] || S.en;
    const plural = new Intl.PluralRules(lang);
    return function t(key, vars = {}) {
      let s = table[key] ?? S.en[key] ?? key;
      if (typeof s === 'object') s = s[plural.select(Number(vars.n) || 0)] ?? s.other;
      s = s.replace(/\{(\w+)\}/g, (_, k) => {
        const v = vars[k];
        if (v == null) return '';
        return typeof v === 'number' ? v.toLocaleString(lang) : String(v);
      });
      return mac ? macKeys(s) : s;
    };
  }

